#!/usr/bin/env node
'use strict';

/**
 * Generate the OpenCode bridge's hook table from hooks/hooks.json.
 *
 * Claude Code runs each ECC hook through a `node -e "<root resolver>"` wrapper
 * that locates the plugin root and then loads one of three bootstraps. The
 * OpenCode bridge already knows the ECC root, so it skips the wrapper and runs
 * the same target directly. This script extracts that target from every
 * hooks.json command, so hooks.json stays the single source of truth:
 *
 *   plugin-hook-bootstrap.js  node <script> <args...>   -> [<script>, ...args]
 *   posttooluse-dispatcher.js .cli() sync|async         -> [posttooluse-dispatcher.js, mode]
 *   lifecycle-hook-bootstrap.js <id> <script> <profiles> <timeout>
 *                                                       -> [lifecycle-hook-bootstrap.js, ...]
 *
 * Profile and disable gating stays inside run-with-flags.js and the
 * dispatchers, so ECC_HOOK_PROFILE and ECC_DISABLED_HOOKS behave the same way
 * under OpenCode as under Claude Code.
 *
 * Usage:
 *   node scripts/build-opencode-hook-table.js          # write the table
 *   node scripts/build-opencode-hook-table.js --check  # exit 1 if it is stale
 */

const fs = require('fs');
const path = require('path');
const { readHooksConfig } = require('./lib/hooks-config');

const REPO_ROOT = path.resolve(__dirname, '..');
const HOOKS_PATH = path.join(REPO_ROOT, 'hooks', 'hooks.json');
const OUTPUT_PATH = path.join(REPO_ROOT, '.opencode', 'ecc', 'bridge', 'hook-table.generated.json');

const BOOTSTRAP_PATTERN = /const s=p\.join\([a-z],'(scripts\/hooks\/[a-z0-9-]+\.js)'\)/;
const SCRIPT_PATTERN = /^scripts\/hooks\/[a-z0-9-]+\.js$/;

/** Events the OpenCode bridge knows how to trigger. */
const SUPPORTED_EVENTS = new Set(['PreToolUse', 'PostToolUse', 'PostToolUseFailure', 'UserPromptSubmit', 'PreCompact', 'SessionStart', 'Stop', 'SessionEnd']);

/**
 * Split a hook command into the bootstrap it loads and the arguments that
 * follow the `node -e "..."` script.
 */
function splitCommand(command) {
  const bootstrap = BOOTSTRAP_PATTERN.exec(command);
  if (!bootstrap) {
    throw new Error(`Unrecognized hook command (no bootstrap): ${command.slice(0, 120)}`);
  }
  const scriptEnd = command.lastIndexOf('"');
  if (scriptEnd === -1) {
    throw new Error(`Unrecognized hook command (no -e script): ${command.slice(0, 120)}`);
  }
  const tail = command.slice(scriptEnd + 1).trim();
  return { bootstrap: bootstrap[1], tail: tail ? tail.split(/\s+/) : [] };
}

function assertScript(script, command) {
  if (!SCRIPT_PATTERN.test(script)) {
    throw new Error(`Unexpected hook script "${script}" in: ${command.slice(0, 120)}`);
  }
}

function toRow(event, entry, hook) {
  const command = String(hook.command || '');
  const { bootstrap, tail } = splitCommand(command);
  let argv;
  let id;
  let kind;

  if (bootstrap.endsWith('/plugin-hook-bootstrap.js')) {
    const [mode, script, ...args] = tail;
    if (mode !== 'node') {
      throw new Error(`Unsupported plugin-hook-bootstrap mode "${mode}" in ${event}`);
    }
    assertScript(script, command);
    argv = [script, ...args];
    if (script.endsWith('/run-with-flags.js')) {
      kind = 'flags';
      id = args[0];
      assertScript(args[1], command);
    } else {
      kind = 'direct';
      id = entry.id;
    }
  } else if (bootstrap.endsWith('/posttooluse-dispatcher.js')) {
    kind = 'dispatcher';
    const mode = tail[0] === 'async' ? 'async' : 'sync';
    argv = [bootstrap, mode];
    id = entry.id || `post:dispatcher:${mode}`;
  } else if (bootstrap.endsWith('/lifecycle-hook-bootstrap.js')) {
    kind = 'lifecycle';
    assertScript(tail[1], command);
    argv = [bootstrap, ...tail];
    id = tail[0];
  } else {
    throw new Error(`Unsupported bootstrap ${bootstrap} in ${event}`);
  }

  if (!id) {
    throw new Error(`Could not determine hook id for ${event} ${JSON.stringify(argv)}`);
  }

  const row = {
    event,
    matcher: typeof entry.matcher === 'string' ? entry.matcher : '',
    id,
    kind,
    argv,
    async: hook.async === true
  };
  if (Number.isFinite(hook.timeout) && hook.timeout > 0) {
    row.timeoutMs = Math.round(hook.timeout * 1000);
  }
  return row;
}

function buildHookTable(hooksPath = HOOKS_PATH) {
  const config = readHooksConfig(hooksPath);
  const rows = [];
  for (const [event, entries] of Object.entries(config.hooks || {})) {
    if (!SUPPORTED_EVENTS.has(event)) {
      throw new Error(`hooks.json event "${event}" has no OpenCode bridge mapping; add one to the bridge and SUPPORTED_EVENTS`);
    }
    for (const entry of entries) {
      for (const hook of entry.hooks || []) {
        if (hook.type && hook.type !== 'command') continue;
        rows.push(toRow(event, entry, hook));
      }
    }
  }
  return {
    $comment: 'Generated by scripts/build-opencode-hook-table.js from hooks/hooks.json. Do not edit by hand.',
    rows
  };
}

function serialize(table) {
  return JSON.stringify(table, null, 2) + '\n';
}

function main(argv = process.argv.slice(2)) {
  const expected = serialize(buildHookTable());
  if (argv.includes('--check')) {
    const current = fs.existsSync(OUTPUT_PATH) ? fs.readFileSync(OUTPUT_PATH, 'utf8') : '';
    if (current !== expected) {
      process.stderr.write(`${path.relative(REPO_ROOT, OUTPUT_PATH)} is stale; run: node scripts/build-opencode-hook-table.js\n`);
      return 1;
    }
    return 0;
  }
  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  fs.writeFileSync(OUTPUT_PATH, expected);
  process.stdout.write(`Wrote ${path.relative(REPO_ROOT, OUTPUT_PATH)}\n`);
  return 0;
}

if (require.main === module) {
  process.exitCode = main();
}

module.exports = { OUTPUT_PATH, SUPPORTED_EVENTS, buildHookTable, serialize, splitCommand, toRow };
